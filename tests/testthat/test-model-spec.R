test_that("Stan demand blocks use conditional inside shares", {
  logit_file <- system.file("stan", "logit_supply.stan", package = "antitrustBayes")
  ces_file <- system.file("stan", "ces_supply.stan", package = "antitrustBayes")
  logit_code <- paste(readLines(logit_file, warn = FALSE), collapse = "\n")
  ces_code <- paste(readLines(ces_file, warn = FALSE), collapse = "\n")

  expect_match(logit_code, "pred_log_s = logit\\(s_out\\) \\+ delta", fixed = FALSE)
  expect_match(ces_code, "pred_log_r = logit\\(R_0\\) \\+ delta", fixed = FALSE)
  expect_false(grepl("pred_log_s = log\\(s_out\\)", logit_code))
  expect_false(grepl("pred_log_r = log\\(R_0\\)", ces_code))
  expect_match(logit_code, "gamma_market - mean_logit_s0_market", fixed = TRUE)
  expect_match(ces_code, "b_market_rot - mean_logit_s0_market", fixed = TRUE)
  expect_match(logit_code, "firm_shareIn", fixed = TRUE)
  expect_match(ces_code, "firm_revShare", fixed = TRUE)
  expect_match(logit_code, "market_sign * a_market", fixed = TRUE)
  expect_match(ces_code, "market_sign * a_market", fixed = TRUE)
  expect_match(logit_code, "prior_lkj - 1.0", fixed = TRUE)
  expect_match(ces_code, "prior_lkj - 1.0", fixed = TRUE)
  expect_false(grepl("implied_s0", logit_code, fixed = TRUE))
  expect_false(grepl("implied_s0", ces_code, fixed = TRUE))
})
